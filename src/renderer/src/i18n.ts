// ── context ────────────────────────────────────────────────────────

interface I18nCtx {
  lang: Lang
  setLang: (l: Lang) => void
  t: (key: string) => string
}

const I18nContext = createContext<I18nCtx>({
  lang: 'zh',
  setLang: () => {},
  t: (k: string) => k,
})

export function I18nProvider({ children }: { children: React.ReactNode }) {
  const [lang, setLangState] = useState<Lang>(() => {
    try {
      const v = localStorage.getItem('vibe-ide-lang')
      if (v === 'en') return 'en'
      if (v === 'zh') return 'zh'
    } catch {}
    // 首次启动无偏好：按系统语言（zh-CN/zh-TW/zh-HK → zh，其余 → en）
    const sys = (typeof navigator !== 'undefined' && navigator.language) || ''
    return sys.toLowerCase().startsWith('zh') ? 'zh' : 'en'
  })

  const setLang = useCallback((l: Lang) => {
    setLangState(l)
    try { localStorage.setItem('vibe-ide-lang', l) } catch {}
  }, [])

  const t = useCallback(
    (key: string) => {
      if (lang === 'en') return EN_MAP[key] || key
      return ZH_MAP[key] || EN_MAP[key] || key
    },
    [lang],
  )

  return React.createElement(I18nContext.Provider, { value: { lang, setLang, t } }, children)
}

export function useI18n() {
  return useContext(I18nContext)
}
