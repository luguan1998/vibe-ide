// 构建期扫描所有 dsh web client plugin，生成 generated-client-plugins.ts。
// context.ts 遍历此清单自动 ctx.plugin 装载，dsh 新增 client plugin 只需
// vibe `npm install <pkg>`，postinstall 自动纳入，无需改 context.ts。
// 数据源与 dsh-client-src-alias.mjs 一致：node_modules/@deepseek-ai 的 dsh.client 标记。
import { readFileSync, readdirSync, existsSync, writeFileSync } from 'node:fs'
import { join } from 'node:path'
import { fileURLToPath } from 'node:url'

const root = fileURLToPath(new URL('..', import.meta.url).href)
const nmRoot = join(root, 'node_modules', '@deepseek-ai')

// vibe 已有等价物或机制替代的 client plugin：不装载。
const EXCLUDE = new Set([
  'ui-layout',                  // vibe 自己管窗口框架，context.ts 用 layout stub 替代
  'ui-directory-picker-browse',  // 与 vibe DirectoryPicker 重复，改用 native 走 host OS 目录对话框
  'modules',                     // loader 机制本身，vibe 手写 ctx.plugin 替代
  'hmr',                         // dev-only 热更新，prod 不需
  'ui-message-feedback',         // 点赞/点踩反馈条，数据落本地 sidecar 不外发，IDE 无此交互需求
])

const found = []
for (const dir of readdirSync(nmRoot)) {
  const pj = join(nmRoot, dir, 'package.json')
  if (!existsSync(pj)) continue
  let j
  try { j = JSON.parse(readFileSync(pj, 'utf8')) } catch { continue }
  const decl = j?.dsh?.client
  if (!decl || decl.platform !== 'web') continue
  const name = j.name // @deepseek-ai/dsh-client-xxx
  // 只管标准 dsh-client-* 命名的 client plugin；非该前缀的（api-gateway/api-remotes/
  // typert-registry/cordis-client-runner/session-log-export）由 context.ts 手写 base
  // 或按需白名单，避免重复装载 / 变量名非法。
  if (!name.startsWith('@deepseek-ai/dsh-client-')) continue
  const short = name.replace('@deepseek-ai/dsh-client-', '')
  if (EXCLUDE.has(short)) continue
  const clientDir = join(nmRoot, dir, 'src', 'client')
  let entry
  if (existsSync(join(clientDir, 'index.ts'))) entry = 'src/client/index.ts'
  else if (existsSync(join(clientDir, 'apply.ts'))) entry = 'src/client/apply.ts'
  else {
    console.warn(`[gen-dsh-client-plugins] skip ${name}: no src/client/{index,apply}.ts`)
    continue
  }
  found.push({ name, short, entry })
}

found.sort((a, b) => a.short.localeCompare(b.short))

const slug = s => s.replace(/-/g, '_')
const lines = [
  '// AUTO-GENERATED by scripts/gen-dsh-client-plugins.mjs — do not edit; run `npm run postinstall` to regenerate.',
  '// 所有 web client plugin（除 vibe 替代/跳过的 exclude：ui-layout/ui-directory-picker-browse/modules/hmr/ui-message-feedback）。',
  '// dsh 新增 client plugin：vibe `npm install <pkg>` 后 postinstall 自动纳入此处，无需改 context.ts。',
  '',
]
for (const p of found) {
  lines.push(`import { apply as apply_${slug(p.short)}, inject as inject_${slug(p.short)} } from '${p.name}/${p.entry}'`)
}
lines.push('')
lines.push('export const dshClientPlugins = [')
for (const p of found) {
  lines.push(`  { apply: apply_${slug(p.short)}, inject: inject_${slug(p.short)} },`)
}
lines.push(']')
lines.push('')

const out = join(root, 'src', 'renderer', 'src', 'dsh', 'generated-client-plugins.ts')
writeFileSync(out, lines.join('\n'))
console.log(`[gen-dsh-client-plugins] generated ${found.length} plugins -> ${out}`)
console.log(found.map(p => p.short).join(', '))
